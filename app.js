const app = document.querySelector("#app");

function esc(value) {
  return String(value).replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[ch]));
}

function codeLines(classes) {
  return classes.map((item) => `
    <p class="code-line">
      <span class="code-group">${esc(item.group)}</span>
      <code>${esc(item.code)}</code>
      <button class="copy" type="button" data-copy="${esc(item.code)}">Copy</button>
    </p>
  `).join("");
}

function renderOverview() {
  const blocks = years.map((year) => `
    <section class="code-block">
      <h2 class="code-year"><a href="#${year.id}">${esc(year.name)}</a></h2>
      ${codeLines(year.classes)}
    </section>
  `).join("");

  const rows = strands.map((strand) => `
    <tr>
      <th scope="row">${esc(strand.name)}</th>
      ${strand.cells.map((cell) => `<td>${esc(cell)}</td>`).join("")}
    </tr>
  `).join("");

  const goals = objectives.map((item) => `<li>${esc(item)}</li>`).join("");

  app.innerHTML = `
    <p class="lead">Open a year, copy the Google Classroom code, and read the booklet from the page you need.</p>
    <p class="note">Same five aims in every course, then a different set of units. Page numbers below match the PDF page, not the small number printed in the corner.</p>
    <div class="codes">${blocks}</div>
    <h2>What each year takes up</h2>
    <table>
      <thead>
        <tr>
          <th>Strand</th>
          <th>1st year · 86 pages</th>
          <th>2nd year · 84 pages</th>
          <th>3rd year · 66 pages</th>
        </tr>
      </thead>
      <tbody>${rows}</tbody>
      <caption>Source: the 2026 booklets’ unit lists. 2nd year algebra also uses negative coordinates; 1st year functions start on PDF page 68.</caption>
    </table>
    <h2>Course aims</h2>
    <ul class="objectives">${goals}</ul>
  `;
}

function renderYear(year) {
  const units = year.units.map((unit) => {
    const topics = unit.topics.map((topic) => `<li>${esc(topic)}</li>`).join("");
    const jumps = unit.jumps.map((jump) => `
      <button class="jump" type="button" data-page="${jump.page}">${esc(jump.label)} · p.${jump.page}</button>
    `).join("");
    return `
      <article class="unit">
        <div class="unit-no">${esc(unit.n)}</div>
        <div>
          <div class="unit-title">
            <h3>${esc(unit.title)}</h3>
            <button class="page-link" type="button" data-page="${unit.page}">p.${unit.page}</button>
          </div>
          <ul class="topics">${topics}</ul>
          ${jumps ? `<div class="jumps">${jumps}</div>` : ""}
        </div>
      </article>
    `;
  }).join("");

  const links = year.links.map((link) => `
    <li><a href="${esc(link.href)}" target="_blank" rel="noreferrer">${esc(link.label)}</a></li>
  `).join("");

  const materials = year.materials.map((item) => `<li>${esc(item)}</li>`).join("");

  app.innerHTML = `
    <div class="year-head">
      <p class="numeral">${esc(year.numeral)}</p>
      <div>
        <h2>${esc(year.name)}</h2>
        <p class="printed">${esc(year.course)} · ${year.pages} pages. ${esc(year.printed)}</p>
      </div>
    </div>
    <div class="split">
      <aside class="side">
        <h3>Google Classroom</h3>
        ${codeLines(year.classes)}
        <h3>Bring to class</h3>
        <ul>${materials}</ul>
        <p class="note">${esc(year.materialsNote)}</p>
        <div class="actions">
          <a href="${esc(year.file)}" target="_blank" rel="noreferrer">Open the PDF</a>
          <a href="${esc(year.file)}" download>Download</a>
        </div>
      </aside>
      <section>
        <h2 class="section-start">Units</h2>
        ${units}
        <h2>Links printed in the booklet</h2>
        <ul class="links">${links}</ul>
      </section>
    </div>
    <section class="pdf-wrap">
      <h2>Booklet</h2>
      <p class="note">Choose a page number above to move the reader. If the reader stays blank, use Open the PDF.</p>
      <iframe id="booklet" title="${esc(year.name)} booklet" data-file="${esc(year.file)}" src="${esc(year.file)}#page=1"></iframe>
    </section>
  `;
}

function currentId() {
  const hash = location.hash.replace("#", "");
  return years.some((year) => year.id === hash) ? hash : "overview";
}

function render() {
  const id = currentId();
  document.querySelectorAll(".year-nav a").forEach((link) => {
    const selected = link.dataset.year === id;
    if (selected) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  if (id === "overview") renderOverview();
  else renderYear(years.find((year) => year.id === id));
  window.scrollTo(0, 0);
}

document.body.addEventListener("click", async (event) => {
  const copyButton = event.target.closest("[data-copy]");
  if (copyButton) {
    const code = copyButton.dataset.copy;
    try {
      await navigator.clipboard.writeText(code);
      const previous = copyButton.textContent;
      copyButton.textContent = "Copied";
      setTimeout(() => { copyButton.textContent = previous; }, 1200);
    } catch {
      copyButton.textContent = code;
    }
    return;
  }

  const pageButton = event.target.closest("[data-page]");
  if (!pageButton) return;
  const frame = document.querySelector("#booklet");
  if (!frame) return;
  const page = pageButton.dataset.page;
  // A new query forces the PDF viewer to load again. Changing only the #page
  // fragment leaves the reader on the page it already opened.
  frame.src = `${frame.dataset.file}?open=${page}-${Date.now()}#page=${page}`;
  frame.scrollIntoView({ behavior: "auto", block: "start" });
});

window.addEventListener("hashchange", render);
render();
